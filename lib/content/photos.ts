const pad = (n: number) => String(n).padStart(3, "0");

export const PHOTOS: Photo[] = ROWS.map(([n, id, caption, rarity]) => ({
  id,
  src: `/photos/photo-${pad(n)}.jpg`,
  caption,
  rarity: rarity ?? "common",
  ...(VIDEO.has(n) ? { video: `/photos/photo-${pad(n)}.mp4` } : {}),
}));

export const PHOTO_BY_ID = new Map(PHOTOS.map((x) => [x.id, x]));

export const getPhoto = (id: string): Photo | undefined => PHOTO_BY_ID.get(id);
